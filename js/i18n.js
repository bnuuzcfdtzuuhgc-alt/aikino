  const detect = () => {
    try { const s = localStorage.getItem(STORE); if (s && DICT[s]) return s; } catch { /* не критично */ }
    return /^(ru|uk|be|kk)/i.test(navigator.language || 'ru') ? 'ru' : 'en';
  };

  let lang = detect();
  const subs = [];

  const tl = (l, key, ...args) => {
    const v = DICT[l] && DICT[l][key] !== undefined ? DICT[l][key] : DICT.ru[key];
    return typeof v === 'function' ? v(...args) : (v === undefined ? key : v);
  };
  const t = (key, ...args) => tl(lang, key, ...args);

  const setMeta = (sel, attr, val) => { const el = document.querySelector(sel); if (el) el.setAttribute(attr, val); };

  function apply(scope = document) {
    scope.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    scope.querySelectorAll('[data-i18n-attr]').forEach(el => {
      el.dataset.i18nAttr.split(';').forEach(pair => {
        const [attr, key] = pair.split(':');
        if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
      });
    });
    scope.querySelectorAll('.lang button').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  }

  function applyPage() {
    document.documentElement.lang = lang;
    document.title = t('meta.title');
    setMeta('meta[name="description"]', 'content', t('meta.desc'));
    setMeta('meta[property="og:title"]', 'content', t('meta.title'));
    setMeta('meta[property="og:description"]', 'content', t('meta.ogdesc'));
    apply();
  }

  function set(next) {
    if (!DICT[next] || next === lang) return;
    lang = next;
    try { localStorage.setItem(STORE, lang); } catch { /* не критично */ }
    applyPage();
    subs.forEach(fn => fn(lang));
  }

  document.addEventListener('click', e => {
    const b = e.target.closest('.lang button');
    if (b) set(b.dataset.lang);
  });

  applyPage();

  window.I18N = {
    get lang() { return lang; },
    t, tl, apply, set,
    onChange: fn => subs.push(fn)
  };
